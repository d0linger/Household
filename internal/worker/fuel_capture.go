package worker

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"image"
	"io"
	"os"
	"os/exec"
	"strings"
	"time"

	"household/internal/store"
	"household/internal/value"
)

type fuelOCRBuffer struct {
	bytes.Buffer
	limit int
}

func (b *fuelOCRBuffer) Write(data []byte) (int, error) {
	if len(data) > b.limit-b.Len() {
		return 0, errors.New("local OCR output limit")
	}
	return b.Buffer.Write(data)
}

func (w *Worker) fuelOCR(ctx context.Context, source store.FuelCaptureSource) (string, error) {
	if !value.ValidUUID(source.StorageKey) || source.SizeBytes < 1 || source.SizeBytes > 10<<20 {
		return "", errors.New("invalid Fuel capture file")
	}
	ctx, cancel := context.WithTimeout(ctx, 25*time.Second)
	defer cancel()
	root, err := os.OpenRoot(w.Cfg.UploadDir)
	if err != nil {
		return "", err
	}
	defer func() { _ = root.Close() }()
	file, err := root.Open(source.StorageKey)
	if err != nil {
		return "", err
	}
	defer func() { _ = file.Close() }()
	stat, err := file.Stat()
	if err != nil || !stat.Mode().IsRegular() || stat.Size() != source.SizeBytes {
		return "", errors.New("fuel capture file size changed")
	}
	input, err := io.ReadAll(io.LimitReader(file, 10<<20+1))
	if err != nil || int64(len(input)) != source.SizeBytes {
		return "", errors.New("fuel capture input limit")
	}
	digest := sha256.Sum256(input)
	if hex.EncodeToString(digest[:]) != source.SHA256 {
		return "", errors.New("fuel capture digest changed")
	}
	if source.MediaType == "application/pdf" {
		if !bytes.HasPrefix(input, []byte("%PDF-")) {
			return "", errors.New("invalid Fuel capture PDF")
		}
		// Only page one is proposed. The review labels this bounded scope.
		temporary, err := os.CreateTemp("", "household-fuel-*.pdf")
		if err != nil {
			return "", err
		}
		name := temporary.Name()
		defer func() { _ = os.Remove(name) }()
		_, writeErr := temporary.Write(input)
		closeErr := temporary.Close()
		if writeErr != nil {
			return "", writeErr
		}
		if closeErr != nil {
			return "", closeErr
		}
		// security: executable/flags are fixed; name is generated by CreateTemp,
		// never supplied by the caller. The process receives no shell command.
		command := exec.CommandContext(ctx, "/usr/bin/pdftoppm", "-f", "1", "-l", "1", "-singlefile", "-scale-to", "3000", "-png", name) // #nosec G204 -- fixed local binary; private CreateTemp filename, no shell
		var raster fuelOCRBuffer
		raster.limit = 16 << 20
		command.Stdout = &raster
		command.Stderr = &fuelOCRBuffer{limit: 8192}
		if err = command.Run(); err != nil {
			return "", err
		}
		input = raster.Bytes()
	} else if source.MediaType != "image/png" && source.MediaType != "image/jpeg" {
		return "", errors.New("unsupported Fuel capture media")
	}
	config, _, err := image.DecodeConfig(bytes.NewReader(input))
	if err != nil || config.Width < 1 || config.Height < 1 || int64(config.Width)*int64(config.Height) > 20_000_000 {
		return "", errors.New("fuel capture image limit")
	}
	command := exec.CommandContext(ctx, "/usr/bin/tesseract", "stdin", "stdout", "-l", "deu+eng", "--psm", "6")
	command.Stdin = bytes.NewReader(input)
	var output fuelOCRBuffer
	output.limit = 65536
	command.Stdout = &output
	command.Stderr = &fuelOCRBuffer{limit: 8192}
	if err = command.Run(); err != nil {
		return "", err
	}
	return strings.ToValidUTF8(output.String(), ""), nil
}
