var backupUploadSlot = make(chan struct{}, 1)

func (s *Server) uploadBackupArchive(w http.ResponseWriter, r *http.Request) {
	id := identity(r)
	if id.Role != "admin" {
		s.fail(w, r, store.ErrForbidden)
		return
	}
	select {
	case backupUploadSlot <- struct{}{}:
		defer func() { <-backupUploadSlot }()
	default:
		s.fail(w, r, store.Invalid{Message: "Eine Backup-Datei wird bereits hochgeladen."})
		return
	}
	overview, err := s.loadBackupOverview(r.Context())
	if err != nil {
		s.fail(w, r, err)
		return
	}
	if !overview.ServiceOnline {
		s.fail(w, r, store.Invalid{Message: "Der Sicherungsdienst ist nicht erreichbar."})
		return
	}
	var pending bool
	err = s.Pool.QueryRow(r.Context(), `SELECT EXISTS(SELECT 1 FROM core.backup_jobs
 WHERE household_id=$1 AND kind='verify' AND target='local' AND state='requested')`, id.HouseholdID).Scan(&pending)
	if err != nil {
		s.fail(w, r, err)
		return
	}
	if pending {
		s.fail(w, r, store.Invalid{Message: "Eine lokale Probewiederherstellung wartet bereits."})
		return
	}
	hc := http.NewResponseController(w)
	_ = hc.SetReadDeadline(time.Now().Add(30 * time.Minute))
	_ = hc.SetWriteDeadline(time.Now().Add(31 * time.Minute))
	r.Body = http.MaxBytesReader(w, r.Body, backupplan.ArchiveLimit)
	defer func() { _ = r.Body.Close() }()
	if r.ContentLength > backupplan.ArchiveLimit {
		backupTooLarge(w, r)
		return
	}
	const header = "age-encryption.org/v1\n"
	body := bufio.NewReader(r.Body)
	magic, err := body.Peek(len(header))
	if err != nil || string(magic) != header {
		s.fail(w, r, store.Invalid{Message: "Wähle eine verschlüsselte Household-Backup-Datei (.tar.age)."})
		return
	}
	directory := backupplan.ExchangeDirectory()
	temp, err := os.CreateTemp(directory, ".partial-")
	if err != nil {
		s.fail(w, r, err)
		return
	}
	defer func() {
		_ = temp.Close()
		_ = os.Remove(temp.Name())
	}()
	if _, err = io.Copy(temp, body); err != nil {
		var limit *http.MaxBytesError
		if errors.As(err, &limit) {
			backupTooLarge(w, r)
			return
		}
		s.fail(w, r, err)
		return
	}
	if err = errors.Join(temp.Sync(), temp.Close()); err != nil {
		s.fail(w, r, err)
		return
	}
	snapshot := backupplan.ArchiveID(time.Now())
	staged := filepath.Join(directory, backupplan.ExchangeName("import", snapshot))
	if err = os.Rename(temp.Name(), staged); err != nil { // #nosec G703 -- both paths are generated by the server
		s.fail(w, r, err)
		return
	}
	queued := false
	defer func() {
		if !queued {
			_ = os.Remove(staged) // #nosec G703 -- generated path for this request
		}
	}()
	tx, err := audit.Begin(r.Context(), s.Pool)
	if err != nil {
		s.fail(w, r, err)
		return
	}
	defer func() { _ = tx.Rollback(context.WithoutCancel(r.Context())) }()
	if err = auth.LockSession(r.Context(), tx, id); err != nil {
		s.fail(w, r, err)
		return
	}
	job := value.UUID()
	_, err = tx.Exec(r.Context(), `INSERT INTO core.backup_jobs(id,household_id,kind,target,snapshot_reference,requested_by)
 VALUES($1,$2,'verify','local',$3,$4)`, job, id.HouseholdID, snapshot, id.UserID)
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == "23505" && pgErr.ConstraintName == "backup_jobs_one_pending" {
		s.fail(w, r, store.Invalid{Message: "Eine lokale Probewiederherstellung wartet bereits."})
		return
	}
	if err == nil {
		err = audit.Event(r.Context(), tx, "core", "backup_jobs", job, "backup_requested", nil)
	}
	if err != nil {
		s.fail(w, r, err)
		return
	}
	// After a commit error PostgreSQL may have accepted the job. The worker
	// reconciles any orphaned import instead of erasing its possibly claimed file.
	queued = true
	if err = tx.Commit(r.Context()); err != nil {
		s.fail(w, r, err)
		return
	}
	s.backupDone(w, r, map[string]string{"id": job}, "Auftrag gespeichert. Der Sicherungsdienst übernimmt ihn in Kürze.")
}

func backupTooLarge(w http.ResponseWriter, r *http.Request) {
	writeJSON(w, http.StatusRequestEntityTooLarge, map[string]string{"error": i18n.Text(requestLocale(r), "Die Backup-Datei überschreitet 32 GiB.")})
}

func localArchiveDirectory() string {
	// The worker trims the configured repository the same way.
	return backupplan.ArchiveDirectory(strings.TrimSpace(os.Getenv("RESTIC_REPOSITORY")))
}

// openBackupDownload opens the file for a snapshot of the repository with this
// label. An offsite download is only served when it was prepared from that label.
func openBackupDownload(target, snapshot, label string) (*os.File, error) {
	name := backupplan.ArchiveName(snapshot)
	if name == "" {
		return nil, os.ErrNotExist
	}
	dir := localArchiveDirectory()
	if target == "offsite" {
		name = backupplan.DownloadName(snapshot, label)
		dir = backupplan.ExchangeDirectory()
		if name == "" {
			return nil, os.ErrNotExist
		}
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	defer func() { _ = root.Close() }()
	return root.Open(name)
}

func archiveDownloadReady(target, snapshot, label string) bool {
	f, err := openBackupDownload(target, snapshot, label)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	st, err := f.Stat()
	return err == nil && st.Mode().IsRegular() && st.Size() > 0
}

func (s *Server) downloadBackupArchive(w http.ResponseWriter, r *http.Request) {
	if identity(r).Role != "admin" {
		s.fail(w, r, store.ErrForbidden)
		return
	}
	target, snapshot := r.PathValue("target"), r.PathValue("snapshot")
	name := backupplan.ArchiveName(snapshot)
	if name == "" || target != "local" && target != "offsite" {
		s.fail(w, r, store.ErrNotFound)
		return
	}
	var label string
	err := s.Pool.QueryRow(r.Context(), `SELECT r.repository_reference FROM core.backup_runs r JOIN core.backup_settings s
 ON r.repository_reference=CASE WHEN $1='local' THEN s.local_label ELSE s.offsite_label END
 WHERE r.state='complete' AND r.repository_kind=$1 AND r.snapshot_reference=$2 LIMIT 1`, target, snapshot).Scan(&label)
	if errors.Is(err, pgx.ErrNoRows) {
		s.fail(w, r, store.ErrNotFound)
		return
	}
	if err != nil {
		s.fail(w, r, err)
		return
	}
	f, err := openBackupDownload(target, snapshot, label)
	if err != nil {
		s.fail(w, r, store.ErrNotFound)
		return
	}
	defer func() { _ = f.Close() }()
	info, err := f.Stat()
	if err != nil || !info.Mode().IsRegular() || info.Size() <= 0 || info.Size() > backupplan.ArchiveLimit {
		s.fail(w, r, store.ErrNotFound)
		return
	}
	_ = http.NewResponseController(w).SetWriteDeadline(time.Now().Add(30 * time.Minute))
	w.Header().Set("Content-Type", "application/octet-stream")
	w.Header().Set("Content-Disposition", `attachment; filename="`+name+`"`)
	w.Header().Set("Cache-Control", "private, no-store")
	http.ServeContent(w, r, name, info.ModTime(), f)
}
